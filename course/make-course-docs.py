import pathlib

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

HERE = pathlib.Path(__file__).resolve().parent

INK = RGBColor(0x14, 0x18, 0x1F)
MUTED = RGBColor(0x5B, 0x64, 0x70)
ACCENT = RGBColor(0x0B, 0x5F, 0xFF)
RED = RGBColor(0xA3, 0x1D, 0x1D)
GREEN = RGBColor(0x0A, 0x7D, 0x4A)


def doc_new(title, subtitle):
    d = Document()
    st = d.styles["Normal"]
    st.font.name = "Calibri"
    st.font.size = Pt(10.5)
    st.font.color.rgb = INK

    h = d.add_paragraph()
    r = h.add_run(title)
    r.bold = True
    r.font.size = Pt(19)
    r.font.color.rgb = INK

    s = d.add_paragraph()
    r = s.add_run(subtitle)
    r.font.size = Pt(10)
    r.font.color.rgb = MUTED
    return d


def h1(d, text):
    p = d.add_paragraph()
    p.paragraph_format.space_before = Pt(16)
    p.paragraph_format.space_after = Pt(5)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(14)
    r.font.color.rgb = ACCENT
    return p


def h2(d, text):
    p = d.add_paragraph()
    p.paragraph_format.space_before = Pt(11)
    p.paragraph_format.space_after = Pt(3)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(11.5)
    return p


def para(d, text, color=None, size=10.5, italic=False):
    """Текст с **жирным** по маркерам."""
    p = d.add_paragraph()
    p.paragraph_format.space_after = Pt(6)
    for i, chunk in enumerate(text.split("**")):
        if not chunk:
            continue
        r = p.add_run(chunk)
        r.bold = i % 2 == 1
        r.italic = italic
        r.font.size = Pt(size)
        if color is not None:
            r.font.color.rgb = color
    return p


def bullet(d, text):
    p = d.add_paragraph(style="List Bullet")
    p.paragraph_format.space_after = Pt(3)
    for i, chunk in enumerate(text.split("**")):
        if not chunk:
            continue
        r = p.add_run(chunk)
        r.bold = i % 2 == 1
        r.font.size = Pt(10.5)
    return p


def mono(d, lines):
    p = d.add_paragraph()
    p.paragraph_format.space_before = Pt(4)
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.left_indent = Pt(14)
    r = p.add_run("\n".join(lines))
    r.font.name = "Consolas"
    r.font.size = Pt(9)
    r.font.color.rgb = INK
    return p


def rule(d):
    p = d.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run("─" * 58)
    r.font.color.rgb = RGBColor(0xC8, 0xCE, 0xD6)
    return p


def table(d, header, rows, widths=None):
    t = d.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for i, htext in enumerate(header):
        cell = t.rows[0].cells[i]
        cell.text = ""
        r = cell.paragraphs[0].add_run(htext)
        r.bold = True
        r.font.size = Pt(9.5)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            for j, chunk in enumerate(str(val).split("**")):
                if not chunk:
                    continue
                r = p.add_run(chunk)
                r.bold = j % 2 == 1
                r.font.size = Pt(9)
    return t


